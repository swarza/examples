/**
 * Copies drizzle/*.sql into lib/migrations.generated.ts, so the app can apply its own migrations
 * on first use (lib/migrate.ts) without shipping the folder. Runs before `next build`.
 */
import { readFile, writeFile } from "node:fs/promises";

const journal = JSON.parse(await readFile(new URL("../drizzle/meta/_journal.json", import.meta.url), "utf8"));
const migrations = [];
for (const entry of journal.entries) {
  const sql = await readFile(new URL(`../drizzle/${entry.tag}.sql`, import.meta.url), "utf8");
  migrations.push({
    tag: entry.tag,
    statements: sql
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean),
  });
}
await writeFile(
  new URL("../lib/migrations.generated.ts", import.meta.url),
  `// Generated by scripts/embed-migrations.mjs from drizzle/. Do not edit.\nexport const migrations: { tag: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`embedded ${migrations.length} migration(s)`);
